#!/bin/bash

############################################################
# Terminal Colours & User Interface
############################################################

#
# Colours
#

RED="\033[0;31m"
GREEN="\033[0;32m"
YELLOW="\033[1;33m"
BLUE="\033[0;34m"
CYAN="\033[0;36m"
WHITE="\033[1;37m"
GREY="\033[0;90m"

RESET="\033[0m"

############################################################
# Header
############################################################

header()
{
    echo
    echo -e "${CYAN}══════════════════════════════════════════════════════${RESET}"
    echo -e "${WHITE}               $1${RESET}"
    echo -e "${CYAN}══════════════════════════════════════════════════════${RESET}"
    echo
}

############################################################
# Section Heading
############################################################

section()
{
    echo
    echo -e "${CYAN}$1${RESET}"
    echo -e "${GREY}------------------------------------------------------${RESET}"
}

############################################################
# Progress Step
############################################################

step()
{
    echo -e "${BLUE}▶${RESET} $1"
}

############################################################
# Success
############################################################

success()
{
    echo -e "${GREEN}✓${RESET} $1"
}

############################################################
# Warning
############################################################

warning()
{
    echo -e "${YELLOW}⚠${RESET} $1"
}

############################################################
# Error
############################################################

error()
{
    echo -e "${RED}✖${RESET} $1"
}

############################################################
# Information
############################################################

info()
{
    echo -e "    ${GREY}$1${RESET}"
}

############################################################
# Fatal Error
############################################################

fatal()
{
    echo
    error "$1"
    echo
    exit 1
}
